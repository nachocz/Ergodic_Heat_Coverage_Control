"""Build the files that the pages in docs/ load, so that they work without CORS requests.

The pages are written as ES modules (docs/js/pages, docs/js/lib, docs/js/sim; the
simulation modules also run under Node.js in tests/web_parity.mjs). Browsers load
ES modules, web fonts, and fetch() requests in CORS mode, which fails where every
document is served in a sandboxed origin without CORS headers (the anonymized pages
of anonymous.4open.science) and on file:// addresses. The pages therefore load:

    docs/js/dist/<page>.js                    each page with its imports, as one classic script
    docs/vendor/katex/katex.inline.min.css    the KaTeX style sheet with its fonts embedded
    docs/data/fields.js                       docs/data/fields.json as a script

Run after editing docs/js or docs/data/fields.json (needs Node.js; npx fetches esbuild):

    python tools/build_web.py

tests/test_web_build.py checks that the built files match their sources.
"""
from __future__ import annotations

import base64
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
ESBUILD = "esbuild@0.24.0"
PAGES = ("landing", "problem", "control", "stability", "player")
# Every module a page can import (the digest of these files is written in each bundle).
SOURCES = ("js/lib", "js/pages", "js/sim", "vendor/three")


def sources_digest() -> str:
    """Digest of the module sources, independent of the line endings of the checkout."""
    digest = hashlib.sha256()
    for folder in SOURCES:
        for path in sorted((DOCS / folder).glob("*.js")):
            digest.update(f"{folder}/{path.name}\n".encode())
            digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
    return digest.hexdigest()[:16]


def bundle_header(page: str, digest: str) -> str:
    return (f"// Generated by tools/build_web.py from docs/js/pages/{page}.js and the modules it imports\n"
            f"// (sources {digest}). Do not edit; edit the modules and run the script again.\n")


def bundle(page: str, digest: str) -> str:
    npx = shutil.which("npx")
    if npx is None:
        sys.exit("npx (Node.js) is needed to bundle the pages")
    result = subprocess.run([npx, "--yes", ESBUILD, f"docs/js/pages/{page}.js", "--bundle", "--format=esm",
                             "--platform=browser", "--legal-comments=inline", "--log-level=warning"],
                            cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.exit(result.stderr)
    code = result.stdout
    if re.search(r"^(import|export)[\s{*]", code, re.MULTILINE):
        sys.exit(f"{page}: the bundle still contains import/export statements")
    # The pages use top-level await: run the bundle in an async function, which makes
    # it a classic script.
    return bundle_header(page, digest) + "(async () => {\n" + code + "})();\n"


def katex_css() -> str:
    folder = DOCS / "vendor" / "katex"
    css = (folder / "katex.min.css").read_text(encoding="utf-8")

    def embed(match: re.Match) -> str:
        data = base64.b64encode((folder / "fonts" / f"{match[1]}.woff2").read_bytes()).decode("ascii")
        return f'url(data:font/woff2;base64,{data}) format("woff2")'

    css = re.sub(r'url\(fonts/(KaTeX_[\w-]+)\.woff2\) format\("woff2"\)'
                 r'(?:,url\(fonts/\1\.woff\) format\("woff"\))?(?:,url\(fonts/\1\.ttf\) format\("truetype"\))?',
                 embed, css)
    if "url(fonts/" in css:
        sys.exit("katex.min.css: a font was not embedded")
    return ("/* KaTeX style sheet (katex.min.css, MIT license, see LICENSE) with the woff2 fonts of fonts/ embedded;\n"
            "   generated by tools/build_web.py. */\n" + css)


def fields_js() -> str:
    text = (DOCS / "data" / "fields.json").read_text(encoding="utf-8").strip()
    json.loads(text)
    return ("// Generated by tools/build_web.py from docs/data/fields.json (examples/export_web_data.py).\n"
            "window.EHCC_FIELDS = " + text + ";\n")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"written: {path.relative_to(ROOT).as_posix()} ({path.stat().st_size / 1024:.0f} kB)")


def main() -> None:
    digest = sources_digest()
    for page in PAGES:
        write(DOCS / "js" / "dist" / f"{page}.js", bundle(page, digest))
    write(DOCS / "vendor" / "katex" / "katex.inline.min.css", katex_css())
    write(DOCS / "data" / "fields.js", fields_js())


if __name__ == "__main__":
    main()
